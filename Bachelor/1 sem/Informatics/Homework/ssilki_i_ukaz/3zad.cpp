#include <iostream>
#include <clocale>

using namespace std;

int main(){
    int a = 4, b = 9;  // Создаём переменные a = 4 и b = 9
    int* p = &a;       // Указатель p хранит адрес переменной a
    int* q = p;        // Указатель q получает тот же адрес, что и p
    int& r = *p;       // Ссылка r связывается с переменной a, на которую указывает p

    p = &b;            // Теперь p указывает на переменную b
    *q += *p;          // К значению a прибавляем значение b, так как q указывает на a
    *p = r - 3;        // В b записываем значение r минус 3
    q = p;              // Теперь q тоже указывает на b
    *q += r;            // К значению b прибавляем значение r, то есть значение a
    cout << a << " " << b << " " << r; // Выводим a, b и r
}
#include <iostream>
#include <clocale>

using namespace std;

int main(){
    int a = 2, b = 5, c = 8; // Создаём переменные a = 2, b = 5, c = 8

    int* p = &a;       // Указатель p хранит адрес переменной a
    int& r = a;        // Ссылка r связывается с переменной a
    int copy = *p;     // Копируем значение a в переменную copy (copy = 2)

    *p = b;            // Записываем значение b в переменную, на которую указывает p (a = 5)
    p = &c;            // Перенаправляем указатель p на переменную c
    r = *p;            // Записываем значение c в a через ссылку r (a = 8)
    *p = b + copy;     // Записываем в c сумму b и copy (c = 5 + 2 = 7)
    p = &b;            // Перенаправляем указатель p на переменную b
    *p = r - copy;     // Записываем в b разность r и copy (b = 8 - 2 = 6)
    r++;               // Увеличиваем a на 1 через ссылку r (a = 9)
    cout << a << " " << b << " " << c << " " << copy; // Выводим итоговые значения
}
#include <iostream>
#include <clocale>

using namespace std;

int main(){
    int a = 10;      // Инициализируем переменную a и записываем в неё 10
    int b = 20;      // Инициализируем переменную b и записываем в неё 20
    int& r = a;      // Создаём ссылку r на переменную a

    r = b;           // Присваиваем переменной a значение переменной b (20)
    r++;             // Увеличиваем значение переменной a на 1
    cout << a << ' ' << b; // Выводим значения переменных a и b через пробел
}
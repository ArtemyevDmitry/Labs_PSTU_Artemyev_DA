#include <iostream>
#include <clocale>

using namespace std;

int main(){
    int a = 5, b = 8; // Создаём переменные a = 5 и b = 8
    int& r = a;       // Создаём ссылку r на переменную a
    int& s = a;       // Создаём ссылку s на ту же переменную a
    int copy = a;     // Копируем текущее значение a в отдельную переменную copy

    r = b;            // Присваиваем a значение b, то есть 8
    s += 2;           // Увеличиваем a на 2 через ссылку s
    b = copy;         // Присваиваем b значение copy, то есть 5
    cout << a << " " << b << " "
         << r << " " << s << " " << copy; // Выводим все значения
}